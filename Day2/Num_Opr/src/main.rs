fn main() {
    //addiction
    let sum = 5 + 10;

    //subtraction
    let difference = 95.5 - 4.3;

    //multiplication
    let product = 4 * 30;

    //division
    let quotient = 56.7 / 32.2;
    let truncated = -5 / 3; //result is -1, because it truncates toward zero

    //remainder
    let remainder = 43 % 5; //modulus operator gives the remainder of the division

    println!("Sum: {sum}, Difference: {difference}, Product: {product}, Quotient: {quotient}, Truncated: {truncated}, Remainder: {remainder}");
}
